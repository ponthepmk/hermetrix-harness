// The built-in PDF writer uses a standard PDF font. It therefore refuses text
// outside printable Basic Latin instead of producing a file whose Thai or CJK
// text silently renders as empty boxes. DOCX/PPTX/XLSX remain full UTF-8 OOXML.
func makeBasicLatinPDF(title string, paragraphs []string) ([]byte, error) {
	lines := append([]string{title}, paragraphs...)
	for _, line := range lines {
		for _, r := range line {
			if r == '\n' || r == '\t' || (r >= 32 && r <= 126) {
				continue
			}
			return nil, fmt.Errorf("native PDF currently supports printable Basic Latin only; use DOCX or PPTX for Unicode text")
		}
	}
	var content strings.Builder
	content.WriteString("BT /F1 20 Tf 72 760 Td ")
	for index, line := range lines {
		if index == 1 {
			content.WriteString(" /F1 11 Tf")
		}
		if index > 0 {
			content.WriteString(" 0 -24 Td")
		}
		content.WriteString(" (" + pdfEscape(line) + ") Tj")
	}
	content.WriteString(" ET")
	stream := content.String()
	objects := []string{
		`<< /Type /Catalog /Pages 2 0 R >>`,
		`<< /Type /Pages /Kids [3 0 R] /Count 1 >>`,
		`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>`,
		`<< /Length ` + strconv.Itoa(len(stream)) + ` >>` + "\nstream\n" + stream + "\nendstream",
		`<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>`,
	}
	var output bytes.Buffer
	output.WriteString("%PDF-1.7\n%\xE2\xE3\xCF\xD3\n")
	offsets := make([]int, len(objects)+1)
	for index, object := range objects {
		offsets[index+1] = output.Len()
		fmt.Fprintf(&output, "%d 0 obj\n%s\nendobj\n", index+1, object)
	}
	xref := output.Len()
	fmt.Fprintf(&output, "xref\n0 %d\n0000000000 65535 f \n", len(objects)+1)
	for index := 1; index <= len(objects); index++ {
		fmt.Fprintf(&output, "%010d 00000 n \n", offsets[index])
	}
	fmt.Fprintf(&output, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(objects)+1, xref)
	return output.Bytes(), nil
}

func pdfEscape(value string) string {
	return strings.NewReplacer(`\\`, `\\\\`, `(`, `\\(`, `)`, `\\)`, "\n", `\n`, "\r", "").Replace(value)
}

func makeOOXML(files map[string]string) ([]byte, error) {
	var output bytes.Buffer
	archive := zip.NewWriter(&output)
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, filepath.ToSlash(name))
	}
	sort.Strings(names)
	for _, name := range names {
		header := &zip.FileHeader{Name: name, Method: zip.Deflate}
		header.SetModTime(time.Date(1980, 1, 1, 0, 0, 0, 0, time.UTC))
		writer, err := archive.CreateHeader(header)
		if err != nil {
			return nil, err
		}
		if _, err := writer.Write([]byte(files[name])); err != nil {
			return nil, err
		}
	}
	if err := archive.Close(); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

func xmlText(value string) string {
	var output bytes.Buffer
	_ = xml.EscapeText(&output, []byte(value))
	return output.String()
}

func xmlAttr(value string) string { return xmlText(value) }
