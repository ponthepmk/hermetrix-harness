const maxDeliverableCells = 20000

// CreateDeliverable builds a portable Office/PDF file and stores it as an
// immutable Artifact. The request is deliberately content-oriented: callers do
// not get to inject raw package paths or XML into an OOXML archive.
func (s *Service) CreateDeliverable(ctx context.Context, input DeliverableInput) (Artifact, error) {
	input.Format = strings.ToLower(strings.TrimPrefix(strings.TrimSpace(input.Format), "."))
	input.Title, input.Actor = strings.TrimSpace(input.Title), strings.TrimSpace(input.Actor)
	if input.Actor == "" || input.Title == "" || utf8.RuneCountInString(input.Title) > 160 {
		return Artifact{}, fmt.Errorf("deliverable actor and title up to 160 characters are required")
	}
	if input.ProjectID != "" {
		if _, err := s.GetProject(ctx, input.ProjectID); err != nil {
			return Artifact{}, err
		}
	}
	if len(input.Paragraphs) > 2000 || len(input.Rows) > maxDeliverableCells || len(input.Slides) > 200 {
		return Artifact{}, fmt.Errorf("deliverable content exceeds the bounded package size")
	}
	cells := 0
	for _, row := range input.Rows {
		cells += len(row)
	}
	if cells > maxDeliverableCells {
		return Artifact{}, fmt.Errorf("spreadsheet exceeds %d cells", maxDeliverableCells)
	}

	var data []byte
	var mimeType, kind string
	var err error
	switch input.Format {
	case "docx":
		data, err = makeDOCX(input.Title, input.Paragraphs)
		mimeType, kind = "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "office_document"
	case "xlsx":
		data, err = makeXLSX(input.Title, input.Rows, input.Paragraphs)
		mimeType, kind = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "office_spreadsheet"
	case "pptx":
		data, err = makePPTX(input.Title, input.Slides, input.Paragraphs)
		mimeType, kind = "application/vnd.openxmlformats-officedocument.presentationml.presentation", "office_presentation"
	case "pdf":
		data, err = makeBasicLatinPDF(input.Title, input.Paragraphs)
		mimeType, kind = "application/pdf", "pdf_document"
	default:
		return Artifact{}, fmt.Errorf("deliverable format must be docx, xlsx, pptx or pdf")
	}
	if err != nil {
		return Artifact{}, err
	}
	name := safeDeliverableName(input.Title) + "." + input.Format
	return s.CreateArtifact(ctx, ArtifactInput{ProjectID: input.ProjectID, SessionID: input.SessionID,
		Name: name, Kind: kind, MIMEType: mimeType, Content: string(data), Metadata: map[string]any{
			"created_by": input.Actor, "generator": "hermetrix-native", "format": input.Format,
			"editable": input.Format != "pdf",
		}})
}

func safeDeliverableName(title string) string {
	var out strings.Builder
	for _, r := range strings.ToLower(title) {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			out.WriteRune(r)
		case r == ' ' || r == '-' || r == '_':
			if out.Len() > 0 && !strings.HasSuffix(out.String(), "-") {
				out.WriteByte('-')
			}
		}
		if out.Len() >= 80 {
			break
		}
	}
	name := strings.Trim(out.String(), "-")
	if name == "" {
		return "hermetrix-deliverable"
	}
	return name
}

func makeDOCX(title string, paragraphs []string) ([]byte, error) {
	if len(paragraphs) == 0 {
		paragraphs = []string{"Generated by Hermetrix."}
	}
	body := wordParagraph(title, true)
	for _, paragraph := range paragraphs {
		body += wordParagraph(paragraph, false)
	}
	files := map[string]string{
		"[Content_Types].xml": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`,
		"_rels/.rels":         `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>`,
		"word/document.xml":   `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>` + body + `<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>`,
	}
	return makeOOXML(files)
}

func wordParagraph(text string, title bool) string {
	properties := ""
	if title {
		properties = `<w:pPr><w:pStyle w:val="Title"/></w:pPr>`
	}
	return `<w:p>` + properties + `<w:r><w:t xml:space="preserve">` + xmlText(text) + `</w:t></w:r></w:p>`
}

func makeXLSX(title string, rows [][]string, paragraphs []string) ([]byte, error) {
	if len(rows) == 0 {
		rows = [][]string{{title}}
		for _, paragraph := range paragraphs {
			rows = append(rows, []string{paragraph})
		}
	}
	var sheet strings.Builder
	for rowIndex, row := range rows {
		sheet.WriteString(`<row r="` + strconv.Itoa(rowIndex+1) + `">`)
		for column, value := range row {
			cell := spreadsheetColumn(column+1) + strconv.Itoa(rowIndex+1)
			sheet.WriteString(`<c r="` + cell + `" t="inlineStr"><is><t xml:space="preserve">` + xmlText(value) + `</t></is></c>`)
		}
		sheet.WriteString(`</row>`)
	}
	files := map[string]string{
		"[Content_Types].xml":        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>`,
		"_rels/.rels":                `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>`,
		"xl/workbook.xml":            `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="` + xmlAttr(sheetTitle(title)) + `" sheetId="1" r:id="rId1"/></sheets></workbook>`,
		"xl/_rels/workbook.xml.rels": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>`,
		"xl/worksheets/sheet1.xml":   `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>` + sheet.String() + `</sheetData></worksheet>`,
	}
	return makeOOXML(files)
}

func spreadsheetColumn(index int) string {
	name := ""
	for index > 0 {
		index--
		name = string(rune('A'+index%26)) + name
		index /= 26
	}
	return name
}

func sheetTitle(title string) string {
	clean := strings.Map(func(r rune) rune {
		if strings.ContainsRune(`[]:*?/\\`, r) {
			return '-'
		}
		return r
	}, title)
	runes := []rune(clean)
	if len(runes) > 31 {
		runes = runes[:31]
	}
	if len(runes) == 0 {
		return "Sheet1"
	}
	return string(runes)
}

func makePPTX(title string, slides []DeliverableSlide, paragraphs []string) ([]byte, error) {
	if len(slides) == 0 {
		slides = []DeliverableSlide{{Title: title, Bullets: paragraphs}}
	}
	var overrides, slideIDs, slideRelationships strings.Builder
	files := map[string]string{
		"_rels/.rels":                                  `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/></Relationships>`,
		"ppt/slideMasters/slideMaster1.xml":            presentationMasterXML,
		"ppt/slideMasters/_rels/slideMaster1.xml.rels": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/theme" Target="../theme/theme1.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideLayout" Target="../slideLayouts/slideLayout1.xml"/></Relationships>`,
		"ppt/slideLayouts/slideLayout1.xml":            presentationLayoutXML,
		"ppt/slideLayouts/_rels/slideLayout1.xml.rels": `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideMaster" Target="../slideMasters/slideMaster1.xml"/></Relationships>`,
		"ppt/theme/theme1.xml":                         presentationThemeXML,
	}
	for index, slide := range slides {
		n := index + 1
		overrides.WriteString(`<Override PartName="/ppt/slides/slide` + strconv.Itoa(n) + `.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>`)
		slideIDs.WriteString(`<p:sldId id="` + strconv.Itoa(255+n) + `" r:id="rId` + strconv.Itoa(n+1) + `"/>`)
		slideRelationships.WriteString(`<Relationship Id="rId` + strconv.Itoa(n+1) + `" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide` + strconv.Itoa(n) + `.xml"/>`)
		files[`ppt/slides/slide`+strconv.Itoa(n)+`.xml`] = presentationSlideXML(slide)
		files[`ppt/slides/_rels/slide`+strconv.Itoa(n)+`.xml.rels`] = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideLayout" Target="../slideLayouts/slideLayout1.xml"/></Relationships>`
	}
	files["[Content_Types].xml"] = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/><Override PartName="/ppt/slideMasters/slideMaster1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideMaster+xml"/><Override PartName="/ppt/slideLayouts/slideLayout1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideLayout+xml"/><Override PartName="/ppt/theme/theme1.xml" ContentType="application/vnd.openxmlformats-officedocument.theme+xml"/>` + overrides.String() + `</Types>`
	files["ppt/presentation.xml"] = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"><p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="rId1"/></p:sldMasterIdLst><p:sldIdLst>` + slideIDs.String() + `</p:sldIdLst><p:sldSz cx="12192000" cy="6858000" type="screen16x9"/><p:notesSz cx="6858000" cy="9144000"/></p:presentation>`
	files["ppt/_rels/presentation.xml.rels"] = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideMaster" Target="slideMasters/slideMaster1.xml"/>` + slideRelationships.String() + `</Relationships>`
	return makeOOXML(files)
}

